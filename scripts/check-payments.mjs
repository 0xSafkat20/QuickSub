import assert from 'node:assert/strict';
import puppeteer from 'puppeteer';
import { randomUUID, randomBytes } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { startTestServer, packageId } from './admin-test-server.mjs';
const env = await startTestServer({ paymentEnv: { PUBLIC_ORIGIN: 'https://shop.example', SSLCOMMERZ_MODE: 'sandbox', SSLCOMMERZ_STORE_ID: 'test', SSLCOMMERZ_STORE_PASSWORD: 'test' } });
let browser;
try {
  const id = randomUUID(), accessCode = randomBytes(32).toString('hex');
  const { createHash } = await import('node:crypto');
  await env.db.query('select quicksub_create_order($1,$2,$3,$4,$5,$6,$7)', [id,createHash('sha256').update(accessCode).digest('hex'),packageId,'Browser buyer','buyer@example.test','Player ID 123',299]);
  await env.db.query('select quicksub_start_payment($1,$2,$3)', [id,'qs_' + 'a'.repeat(24),'buyer@example.test']);
  browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setRequestInterception(true);
  page.on('request', r => r.url().startsWith(env.base) || r.url().startsWith('data:') ? r.continue() : r.abort());
  await page.setViewport({ width: 390, height: 844 });
  await page.goto(env.base + '/?payment=return', { waitUntil: 'networkidle0' });
  await page.waitForSelector('[aria-label="Track your order"]');
  const inputs = await page.$$('form input');
  await inputs[0].type(id); await inputs[1].type(accessCode);
  await page.click('form button');
  await page.waitForFunction(() => document.body.innerText.includes('Verification pending'));
  assert.equal(await page.$eval('button[type="submit"], form button', e => !!e), true);
  assert.ok(await page.$('input[type="email"]'));
  assert.ok(await page.$('input[type="tel"]'));
  assert.ok(await page.$('input[type="checkbox"]'));
  await env.db.query('select quicksub_settle_payment($1,$2,$3)', ['qs_' + 'a'.repeat(24),'verified','bank-browser']);
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Check payment status').click());
  await page.waitForFunction(() => document.body.innerText.includes('Payment confirmed'));
  assert.equal(await page.$('input[type="email"]'), null);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mkdir('deliverables/payment-preview', { recursive: true });
  await page.screenshot({ path: 'deliverables/payment-preview/customer.png', fullPage: true });
  await page.goto(env.base + '/admin', { waitUntil: 'networkidle0' });
  await page.type('input[type="email"]','owner@example.test');
  await page.type('input[type="password"]','test-password');
  await page.click('form button');
  await page.waitForFunction(() => document.body.innerText.includes('Your store at a glance'));
  await page.setViewport({ width: 1440, height: 1000 });
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Orders').click());
  await page.waitForFunction(() => document.body.innerText.includes('Find a gateway transaction'));
  await page.type('input[minlength="3"]','bank-browser');
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Find payment').click());
  await page.waitForFunction(() => document.body.innerText.includes('bank-browser') && document.body.innerText.includes('Gateway payment history'));
  await page.screenshot({ path: 'deliverables/payment-preview/admin.png', fullPage: true });
  await page.select('.qs-payment-box select', 'completed');
  await page.type('.qs-payment-box .qs-payment-box input', 'refund-browser');
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Save refund record').click());
  await page.waitForFunction(() => document.body.innerText.includes('Refund: completed'));
  assert.deepEqual(errors, []);
  console.log('PASS: mobile return page, receipt access, pending/confirmed states, admin payment search and refund recording, no browser errors.');
} finally { if (browser) await browser.close(); await env.close(); }
